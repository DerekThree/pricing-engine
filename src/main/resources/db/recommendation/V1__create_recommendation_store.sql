create table recommendation_batches (
    batch_id uuid primary key
);

create table account_recommendations (
    id bigint generated by default as identity primary key,
    batch_id uuid not null,
    account_number varchar(25) not null,
    status varchar(30) not null,
    pricing_plan_code varchar(25),
    constraint fk_account_recommendations_batch
        foreign key (batch_id) references recommendation_batches (batch_id),
    constraint uk_account_recommendations_batch_account unique (batch_id, account_number)
);

create table fee_request_recommendations (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    fee_request_id bigint not null,
    status varchar(35) not null,
    decision varchar(10),
    amount numeric,
    constraint fk_fee_recommendations_account
        foreign key (account_id) references account_recommendations (id),
    constraint uk_fee_recommendations_account_request unique (account_id, fee_request_id),
    constraint chk_fee_recommendations_amount check (amount >= 0)
);

create table recommendation_eligibility_reasons (
    fee_recommendation_id bigint not null,
    reason_code varchar(25) not null,
    primary key (fee_recommendation_id, reason_code),
    constraint fk_recommendation_reasons_fee
        foreign key (fee_recommendation_id) references fee_request_recommendations (id)
);

create table recommendation_outbox (
    batch_id uuid primary key,
    processed boolean not null default false,
    constraint fk_recommendation_outbox_batch
        foreign key (batch_id) references recommendation_batches (batch_id)
);
